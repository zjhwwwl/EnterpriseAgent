"""Official PostgreSQL checkpoints with migration-only DDL and per-thread locking.

Thread IDs are generated by AgentRepository, and the Service must establish
ownership before calling this internal runtime. API request JSON cannot supply
RunnableConfig or query the SDK saver directly.
"""

import asyncio
import hashlib
import logging
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from importlib.metadata import version
from uuid import UUID

from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
from psycopg import Error as PsycopgError
from psycopg.rows import dict_row
from psycopg_pool import AsyncConnectionPool, PoolClosed, PoolTimeout, TooManyRequests
from sqlalchemy.engine import make_url

from enterprise_agent.domain_errors import BusinessError

logger = logging.getLogger("enterprise_agent.agent.checkpoint")
SDK_VERSION = "3.1.2"
SDK_MIGRATION_COUNT = 10


def thread_lock_key(thread_id: str) -> int:
    """Stable signed int64, namespaced independently from business lock keys."""
    normalized = str(UUID(thread_id))
    digest = hashlib.blake2b(
        f"EnterpriseAgent/checkpoint/thread/{normalized}".encode("ascii"), digest_size=8
    ).digest()
    return int.from_bytes(digest, "big", signed=True)


class AgentCheckpointRuntime:
    def __init__(self, database_url: str, *, pool_size: int = 5):
        if not 2 <= pool_size <= 10:
            raise ValueError("Checkpoint pool_size must be between 2 and 10")
        parsed = make_url(database_url)
        if parsed.get_backend_name() != "postgresql":
            raise ValueError("Agent checkpoints require PostgreSQL")
        if version("langgraph-checkpoint-postgres") != SDK_VERSION:
            raise RuntimeError("Checkpoint SDK version changed; review the Alembic migration")
        # Driver suffix belongs to SQLAlchemy; psycopg accepts a PostgreSQL URI.
        conninfo = parsed.set(drivername="postgresql").render_as_string(hide_password=False)
        self.pool = AsyncConnectionPool(
            conninfo=conninfo,
            kwargs={
                "autocommit": True,
                "prepare_threshold": 0,
                "row_factory": dict_row,
                "connect_timeout": 3,
                "options": (
                    "-c search_path=ea_checkpoint,public "
                    "-c statement_timeout=5000 -c lock_timeout=1000"
                ),
            },
            min_size=1,
            max_size=pool_size,
            timeout=3,
            max_waiting=20,
            reconnect_timeout=3,
            open=False,
            name="ea_checkpoint",
            check=AsyncConnectionPool.check_connection,
        )
        self._saver: AsyncPostgresSaver | None = None
        self._open_lock = asyncio.Lock()
        # A running graph holds one advisory-lock connection. Always leave one
        # pool slot for SDK cursor/readiness queries, even under saturation.
        self._execution_slots = asyncio.Semaphore(pool_size - 1)
        self._closed = False

    @property
    def saver(self) -> AsyncPostgresSaver:
        if self._saver is None or self._closed:
            raise BusinessError("agent_unavailable", "Agent 持久化尚未就绪。", 503)
        return self._saver

    async def open(self) -> None:
        async with self._open_lock:
            if self._closed:
                raise BusinessError("agent_unavailable", "Agent 持久化已关闭。", 503)
            if self._saver is not None:
                return
            try:
                await self.pool.open(wait=True, timeout=5)
            except (PoolTimeout, PsycopgError):
                raise BusinessError("agent_unavailable", "Agent 持久化连接失败。", 503) from None
            self._saver = AsyncPostgresSaver(
                self.pool,
                serde=JsonPlusSerializer(
                    allowed_json_modules=None,
                    allowed_msgpack_modules=None,
                    pickle_fallback=False,
                ),
            )
            # All schema/table creation lives in 0003_agent. No saver.setup().

    async def is_ready(self) -> bool:
        if self._saver is None or self._closed:
            return False
        try:
            async with asyncio.timeout(3), self.pool.connection() as connection:
                row = await (
                    await connection.execute(
                        """
                        SELECT
                          (SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolbypassrls
                           FROM pg_roles WHERE rolname = current_user) AS unsafe_role,
                          has_schema_privilege(current_user, 'ea_checkpoint', 'USAGE') AS can_use,
                          has_schema_privilege(current_user, 'ea_checkpoint', 'CREATE')
                            AS can_create,
                          (SELECT bool_and(has_table_privilege(current_user, name, privilege))
                           FROM unnest(ARRAY['ea_checkpoint.checkpoints',
                             'ea_checkpoint.checkpoint_blobs', 'ea_checkpoint.checkpoint_writes'])
                             AS t(name)
                           CROSS JOIN unnest(ARRAY['SELECT','INSERT','UPDATE']) AS p(privilege))
                             AS can_save,
                          (SELECT bool_or(has_table_privilege(current_user, name, 'DELETE'))
                           FROM unnest(ARRAY['ea_checkpoint.checkpoints',
                             'ea_checkpoint.checkpoint_blobs', 'ea_checkpoint.checkpoint_writes'])
                             AS t(name)) AS can_delete,
                          has_table_privilege(current_user, 'ea_checkpoint.checkpoint_migrations',
                            'SELECT') AS can_read_versions,
                          has_table_privilege(current_user, 'ea_checkpoint.checkpoint_migrations',
                            'INSERT,UPDATE,DELETE')
                          OR has_any_column_privilege(current_user,
                            'ea_checkpoint.checkpoint_migrations', 'INSERT')
                          OR has_any_column_privilege(current_user,
                            'ea_checkpoint.checkpoint_migrations', 'UPDATE') AS can_change_versions,
                          (SELECT array_agg(v ORDER BY v)
                           FROM ea_checkpoint.checkpoint_migrations) AS versions
                        """
                    )
                ).fetchone()
                return bool(
                    row
                    and row["unsafe_role"] is False
                    and row["can_use"] is True
                    and row["can_create"] is False
                    and row["can_save"] is True
                    and row["can_delete"] is False
                    and row["can_read_versions"] is True
                    and row["can_change_versions"] is False
                    and row["versions"] == list(range(SDK_MIGRATION_COUNT))
                )
        except Exception as exc:
            logger.warning(
                "Agent checkpoint readiness failed",
                extra={"event": "agent_checkpoint_not_ready", "exception_type": type(exc).__name__},
            )
            return False

    @asynccontextmanager
    async def thread_lock(self, thread_id: str) -> AsyncIterator[None]:
        """Reject concurrent workers for this thread without holding a SQL transaction.

        The reserved pool connection remains checked out until graph/checkpoint
        work finishes. It is distinct from SDK cursor connections and Service
        transactions, preventing row-lock cycles in refund creation.
        """
        _ = self.saver  # Fail closed before checking out a connection.
        key = thread_lock_key(thread_id)
        try:
            await asyncio.wait_for(self._execution_slots.acquire(), timeout=3)
        except TimeoutError:
            raise BusinessError(
                "agent_unavailable", "Agent 执行容量已满，请稍后重试。", 503
            ) from None
        try:
            try:
                connection = await self.pool.getconn()
            except (PoolTimeout, PoolClosed, TooManyRequests):
                raise BusinessError("agent_unavailable", "Agent 持久化连接不可用。", 503) from None
            acquired = False
            outcome_known = False
            try:
                try:
                    row = await (
                        await connection.execute(
                            "SELECT pg_try_advisory_lock(%s) AS locked", (key,)
                        )
                    ).fetchone()
                except PsycopgError:
                    raise BusinessError("agent_unavailable", "Agent 会话锁不可用。", 503) from None
                outcome_known = row is not None and type(row.get("locked")) is bool
                if not outcome_known:
                    raise BusinessError("agent_unavailable", "Agent 会话锁状态不可用。", 503)
                acquired = row["locked"]
                if not acquired:
                    raise BusinessError("agent_session_busy", "会话正在执行，请稍后重试。", 409)
                yield
            finally:
                try:
                    if not outcome_known:
                        # Cancellation can land after PostgreSQL acquired the
                        # lock but before execute()/fetchone() returns to Python.
                        await connection.close()
                    elif acquired:
                        async with asyncio.timeout(2):
                            unlocked = await (
                                await connection.execute(
                                    "SELECT pg_advisory_unlock(%s) AS unlocked", (key,)
                                )
                            ).fetchone()
                            if not unlocked or unlocked["unlocked"] is not True:
                                await connection.close()
                except BaseException as exc:
                    # Never return a possibly lock-bearing connection to the pool.
                    await connection.close()
                    if isinstance(exc, asyncio.CancelledError):
                        raise
                finally:
                    await self.pool.putconn(connection)
        finally:
            self._execution_slots.release()

    async def close(self) -> None:
        self._closed = True
        self._saver = None
        await self.pool.close()
